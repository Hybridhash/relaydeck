"""Generate src/relaydeck/contracts/grapheme_data.py from the Unicode Character Database.

Usage: python scripts/gen_grapheme_data.py UCD_DIR
UCD_DIR holds GraphemeBreakProperty.txt, emoji_data.txt and DerivedCoreProperties.txt.
Hangul LV/LVT syllables are computed from their code point, so they are not tabulated.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src/relaydeck/contracts/grapheme_data.py"
GCB_CODES = {
    "Prepend": "Prepend",
    "CR": "CR",
    "LF": "LF",
    "Control": "Control",
    "Extend": "Extend",
    "Regional_Indicator": "RI",
    "SpacingMark": "SpacingMark",
    "L": "L",
    "V": "V",
    "T": "T",
    "ZWJ": "ZWJ",
}
LINE = re.compile(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([A-Za-z_]+)(?:\s*;\s*([A-Za-z_]+))?")


def read(path: Path) -> list[tuple[int, int, str, str]]:
    rows = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        match = LINE.match(raw.split("#", 1)[0].strip())
        if match:
            low, high, first, second = match.groups()
            rows.append((int(low, 16), int(high or low, 16), first, second or ""))
    return rows


def merge(rows: list[tuple[int, int, str]]) -> list[tuple[int, int, str]]:
    merged: list[tuple[int, int, str]] = []
    for low, high, kind in sorted(rows):
        if merged and merged[-1][2] == kind and merged[-1][1] + 1 == low:
            merged[-1] = (merged[-1][0], high, kind)
        else:
            merged.append((low, high, kind))
    return merged


def table(rows: list[tuple[int, int, str]]) -> str:
    return "\n".join(f"{low:04X}-{high:04X} {kind}" for low, high, kind in merge(rows))


def main(source: Path) -> None:
    gcb = [
        (low, high, GCB_CODES[kind])
        for low, high, kind, _ in read(source / "GraphemeBreakProperty.txt")
        if kind in GCB_CODES
    ]
    pictographic = [
        (low, high, "Pict")
        for low, high, kind, _ in read(source / "emoji_data.txt")
        if kind == "Extended_Pictographic"
    ]
    incb = [
        (low, high, second)
        for low, high, kind, second in read(source / "DerivedCoreProperties.txt")
        if kind == "InCB" and second in ("Linker", "Consonant", "Extend")
    ]
    version = re.search(r"-(\d+\.\d+\.\d+)", (source / "GraphemeBreakProperty.txt").read_text())
    text = f'''"""Unicode {version.group(1) if version else ""} grapheme data. Generated by
scripts/gen_grapheme_data.py from GraphemeBreakProperty.txt, emoji_data.txt and
DerivedCoreProperties.txt (InCB). Do not edit. Unicode data files: see UNICODE_LICENSE.txt in
tests/fixtures/unicode/."""

# One "FIRST-LAST KIND" range per line, sorted and non-overlapping.
GRAPHEME_BREAK = """
{table(gcb)}
"""

EXTENDED_PICTOGRAPHIC = """
{table(pictographic)}
"""

INDIC_CONJUNCT_BREAK = """
{table(incb)}
"""
'''
    OUT.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
